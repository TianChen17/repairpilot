from __future__ import annotations

import asyncio
import uuid
from pathlib import Path

from .config import Settings
from .datahub_mcp import DataHubContextError, DataHubMCPClient
from .deepseek import DeepSeekRepairGenerator, RepairGenerationError
from .models import (
    ApprovalRecord,
    ContextSnapshot,
    EvidenceItem,
    EvidenceReceipt,
    IncidentRecord,
    IncidentState,
    RiskAction,
    utc_now,
)
from .policy import ChangeFacts, assess_risk
from .store import IncidentStore
from .warehouse import WarehouseRunner, WarehouseValidationError


class IncidentOrchestrator:
    def __init__(
        self,
        settings: Settings,
        store: IncidentStore,
        datahub: DataHubMCPClient,
        generator: DeepSeekRepairGenerator,
        warehouse: WarehouseRunner,
    ) -> None:
        self.settings = settings
        self.store = store
        self.datahub = datahub
        self.generator = generator
        self.warehouse = warehouse
        self.run_lock = asyncio.Lock()

    def start(self, mode: str) -> IncidentRecord:
        run_id = str(uuid.uuid4())
        record = self.store.create(IncidentRecord(run_id=run_id, mode=mode))
        asyncio.create_task(self._investigate_and_validate(record))
        return record

    async def reset(self) -> None:
        if self.run_lock.locked():
            raise RuntimeError("A live incident is currently running")
        await asyncio.to_thread(self.warehouse.reset_demo_schemas)
        self.store.reset()

    async def approve(self, record: IncidentRecord, decision: str, actor: str) -> IncidentRecord:
        if record.state != IncidentState.AWAITING_APPROVAL:
            raise ValueError("Incident is not awaiting approval")
        record.approval = ApprovalRecord(decision=decision, actor=actor)
        self.store.save(record)
        if decision == "reject":
            await self.store.transition(
                record, IncidentState.REJECTED, "Owner rejected the repair; release remains blocked"
            )
            self._write_evidence_receipt(record)
            return record
        await self.store.transition(record, IncidentState.APPROVED, f"Repair approved by {actor}")
        async with self.run_lock:
            await self._publish_and_learn(record)
        return record

    async def _investigate_and_validate(self, record: IncidentRecord) -> None:
        if self.run_lock.locked():
            record.error = "Another judge run is active"
            await self.store.transition(record, IncidentState.MANUAL_REVIEW, record.error)
            return
        async with self.run_lock:
            try:
                if record.mode == "replay":
                    context = self._replay_context()
                else:
                    context = await self.datahub.collect_context()
                record.context = context
                record.evidence.extend(context.evidence)
                self.store.save(record)
                await self.store.transition(
                    record, IncidentState.CONTEXT_COLLECTED, "DataHub MCP context verified"
                )

                risk = assess_risk(context, ChangeFacts(breaking_schema_change=True))
                record.risk = risk
                record.evidence.append(
                    EvidenceItem(
                        source="policy",
                        tool="deterministic_policy",
                        summary=risk.rationale,
                        payload=risk.model_dump(mode="json"),
                    )
                )
                self.store.save(record)
                await self.store.transition(
                    record,
                    IncidentState.POLICY_EVALUATED,
                    f"Risk {risk.score}/100; action {risk.action}",
                )
                if risk.action != RiskAction.BLOCK:
                    raise RuntimeError("Canonical demo did not produce the required BLOCK decision")
                await self.store.transition(
                    record, IncidentState.BLOCKED, "Unsafe source change blocked before release"
                )

                proposal = await self.generator.generate(
                    context, risk, replay=record.mode == "replay"
                )
                record.repair = proposal
                self.store.save(record)
                await self.store.transition(
                    record,
                    IncidentState.REPAIR_PROPOSED,
                    "Bounded compatibility repair generated by DeepSeek V4 Flash",
                )

                await self.store.transition(
                    record, IncidentState.VALIDATING, "Running isolated dbt build"
                )
                validation = await asyncio.to_thread(
                    self.warehouse.validate_repair, record.run_id, proposal
                )
                record.validation = validation
                record.evidence.append(
                    EvidenceItem(
                        source="dbt",
                        tool="dbt_build",
                        summary="Breaking failure reproduced and compatibility repair verified",
                        payload=validation.model_dump(mode="json"),
                    )
                )
                self.store.save(record)
                await self.store.transition(
                    record,
                    IncidentState.VERIFIED,
                    f"dbt build passed with {validation.tests_passed} tests",
                )
                await self.store.transition(
                    record,
                    IncidentState.AWAITING_APPROVAL,
                    "Verified repair is waiting for Revenue Analytics owner approval",
                )
                self._write_evidence_receipt(record)
            except DataHubContextError as exc:
                record.error = str(exc)
                await self.store.transition(
                    record,
                    IncidentState.CONTEXT_UNAVAILABLE,
                    "Fail closed: DataHub context unavailable",
                )
            except (WarehouseValidationError, RepairGenerationError) as exc:
                record.error = str(exc)
                await self.store.transition(
                    record, IncidentState.VALIDATION_FAILED, f"Fail closed: {exc}"
                )
            except Exception as exc:  # noqa: BLE001
                record.error = str(exc)
                await self.store.transition(
                    record,
                    IncidentState.MANUAL_REVIEW,
                    "Unexpected failure; manual review required",
                )
            finally:
                self.store.save(record)

    async def _publish_and_learn(self, record: IncidentRecord) -> None:
        assert record.context and record.risk and record.repair and record.validation
        try:
            record.pull_request_url = self.settings.github_canonical_pr_url or None
            self.store.save(record)
            await self.store.transition(
                record, IncidentState.PUBLISHED, "Validated repair patch published for review"
            )
            incident_markdown = self._incident_markdown(record)
            runbook_markdown = self._runbook_markdown()
            if record.mode == "replay":
                from .models import WritebackReceipt

                writeback = WritebackReceipt(
                    incident_document_urn=f"urn:li:document:replay-{record.run_id}",
                    runbook_document_urn="urn:li:document:replay-safe-column-rename",
                    updated_entity_urns=[record.context.asset_urn],
                    assertion_urns=["urn:li:assertion:replay-gross-revenue-not-null"],
                )
            else:
                writeback = await self.datahub.write_back(
                    run_id=record.run_id,
                    incident_markdown=incident_markdown,
                    runbook_markdown=runbook_markdown,
                    patch_sha256=record.validation.patch_sha256,
                    invocation_id=record.validation.invocation_id,
                )
            record.writeback = writeback
            self.store.save(record)
            await self.store.transition(
                record,
                IncidentState.LEARNED,
                "Incident evidence and reusable runbook written back to DataHub",
            )
            self._write_evidence_receipt(record)
        except Exception as exc:  # noqa: BLE001
            record.error = str(exc)
            await self.store.transition(
                record,
                IncidentState.MANUAL_REVIEW,
                "Repair remains safe; knowledge writeback failed",
            )
            self._write_evidence_receipt(record)

    def _write_evidence_receipt(self, record: IncidentRecord) -> Path | None:
        if not record.risk or not record.validation:
            return None
        writeback_urns: list[str] = []
        if record.writeback:
            writeback_urns = [
                record.writeback.incident_document_urn,
                record.writeback.runbook_document_urn,
                *record.writeback.updated_entity_urns,
                *record.writeback.assertion_urns,
            ]
        receipt = EvidenceReceipt(
            run_id=record.run_id,
            mode=record.mode,
            generated_at=utc_now(),
            state=record.state,
            datahub_urns=[record.context.asset_urn, record.context.column_urn]
            if record.context
            else [],
            policy_version=record.risk.policy_version,
            risk_score=record.risk.score,
            risk_action=record.risk.action,
            matched_rules=record.risk.matched_rules,
            model=self.settings.deepseek_model,
            base_commit=record.validation.base_commit,
            repair_commit=record.validation.repair_commit,
            patch_sha256=record.validation.patch_sha256,
            dbt_invocation_id=record.validation.invocation_id,
            approval=record.approval,
            pull_request_url=record.pull_request_url,
            writeback_urns=writeback_urns,
        )
        artifact_dir = self.settings.repairpilot_runtime_dir / "artifacts" / record.run_id
        artifact_dir.mkdir(parents=True, exist_ok=True)
        path = artifact_dir / "evidence-receipt.json"
        path.write_text(receipt.model_dump_json(indent=2))
        return path

    @staticmethod
    def _incident_markdown(record: IncidentRecord) -> str:
        assert record.risk and record.validation and record.repair
        return f"""# RepairPilot Incident {record.run_id}

**Status:** Verified and owner-approved

**Root cause:** {record.repair.root_cause}

**Risk:** {record.risk.level} ({record.risk.score}/100)

**Policy action:** {record.risk.action}

**Patch SHA-256:** `{record.validation.patch_sha256}`

**dbt invocation:** `{record.validation.invocation_id}`

## Evidence

- Original breaking rename was reproduced and blocked.
- Compatibility alias preserves `gross_amount`.
- Controlled downstream model migrated to `gross_revenue`.
- All selected dbt models and tests passed.
"""

    @staticmethod
    def _runbook_markdown() -> str:
        return """# Safe dbt Column Rename Runbook

1. Query DataHub column lineage, ownership, governance tags, assertions, and usage.
2. Fail closed if context cannot be verified.
3. Keep the old field as a compatibility alias for a defined migration window.
4. Migrate controlled consumers and add a contract assertion for the new field.
5. Run the affected dbt selection in an isolated schema.
6. Require the accountable owner to approve verified high-risk repairs.
7. Publish the evidence receipt and write the reusable learning back to DataHub.
"""

    @staticmethod
    def _replay_context() -> ContextSnapshot:
        return ContextSnapshot(
            asset_urn=DataHubMCPClient.ASSET_URN,
            column_urn=DataHubMCPClient.COLUMN_URN,
            owners=["Revenue Analytics"],
            tags=["Tier1", "FinancialMetric", "SLA-1h"],
            domain="Finance Analytics",
            downstream_assets=[
                "int_order_revenue",
                "fct_daily_revenue",
                "mart_executive_revenue",
            ],
            downstream_dashboards=["Executive Revenue Pulse"],
            queries=["SELECT region, SUM(gross_amount) FROM mart_executive_revenue"],
            assertions=["not_null_gross_amount", "accepted_values_order_status"],
            schema_fields=["order_id", "ordered_at", "region", "currency", "gross_amount"],
            evidence=[
                EvidenceItem(
                    source="datahub_mcp",
                    tool="replay_fixture",
                    summary="Clearly labeled replay of a previously captured MCP evidence bundle",
                    payload={"mode": "replay"},
                )
            ],
        )
